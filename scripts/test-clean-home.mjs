import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {mkdir} from 'node:fs/promises';
await mkdir('.sites-runtime/tests',{recursive:true});
await build({entryPoints:['worker/day-plan.ts','worker/profile.ts'],outdir:'.sites-runtime/tests/clean',bundle:true,platform:'node',format:'esm',logLevel:'silent'});
const {prepareDayDrafts}=await import('../.sites-runtime/tests/clean/day-plan.js');
const {profileSchema}=await import('../.sites-runtime/tests/clean/profile.js');
const settings={timezone:'Europe/Madrid',defaultTravelMinutes:45};
const base={title:'Clase',kind:'event',date:'2026-10-16',time:'09:00',duration:60,nextStep:'Abrir los apuntes.',ambiguous:'',recurrence:'none'};
let [draft]=prepareDayDrafts([base],settings);
assert.equal(draft.reminder,true);assert.equal(draft.travelMinutes,45);assert.equal(draft.timezone,'Europe/Madrid');
[draft]=prepareDayDrafts([{...base,title:'Repasar fracciones',kind:'task',time:null,purpose:'study',reminder:true}],settings);
assert.equal(draft.date,'2026-10-16');assert.equal(draft.time,null);assert.equal(draft.reminder,false);assert.equal(draft.purpose,'study');
[draft]=prepareDayDrafts([{...base,date:null}],settings);assert.equal(draft.date,null);assert.match(draft.ambiguous,/Confirma/);
[draft]=prepareDayDrafts([{...base,ambiguous:'¿Por la mañana?'}],settings);assert.equal(draft.time,null);assert.equal(draft.reminder,false);
[draft]=prepareDayDrafts([{...base,purpose:null}],settings);assert.equal(draft.purpose,undefined);
const profile={audience:'adult',age:null,country:'España',course:'',guardianConsent:false,aiConsent:false,completed:true,studying:false,useCases:['home','work']};
assert.equal(profileSchema.safeParse(profile).success,true);
assert.equal(profileSchema.safeParse({...profile,useCases:[]}).success,false);
assert.equal(profileSchema.safeParse({...profile,studying:true,subjects:'',studyLevel:'secondary'}).success,false);
assert.equal(profileSchema.safeParse({...profile,studying:true,subjects:'Matemáticas',studyLevel:'secondary'}).success,true);
assert.equal(profileSchema.safeParse({...profile,audience:'teen',age:13,guardianConsent:false}).success,false);
assert.equal(profileSchema.safeParse({...profile,audience:'teen',age:13,guardianConsent:true}).success,true);
console.log('Clean-home rules passed: context, optional AI, age/guardian, timed reminders, travel and unscheduled Later.');
